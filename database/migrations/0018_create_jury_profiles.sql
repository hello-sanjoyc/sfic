CREATE TABLE IF NOT EXISTS public.jury_profiles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name character varying(200) NOT NULL,
    email character varying(255) NOT NULL UNIQUE,
    mobile character varying(20) NOT NULL,
    scope character varying(20) NOT NULL CHECK (scope IN ('State', 'District')),
    state_id bigint NOT NULL REFERENCES public.states(id),
    district_id bigint REFERENCES public.districts(id),
    address text,
    city character varying(120),
    pin_code character varying(12),
    organisation_name character varying(240),
    designation character varying(240),
    professional_experience_years integer CHECK (professional_experience_years >= 0),
    cv_storage_key text,
    cv_original_file_name character varying(255),
    avatar_storage_key text,
    avatar_original_file_name character varying(255),
    email_verified_at timestamp with time zone,
    profile_completed_at timestamp with time zone,
    is_active boolean DEFAULT false NOT NULL,
    invited_by_user_id bigint NOT NULL REFERENCES public.users(id),
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT jury_profiles_district_scope CHECK ((scope = 'State' AND district_id IS NULL) OR (scope = 'District' AND district_id IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS public.jury_profile_categories (
    jury_profile_id bigint NOT NULL REFERENCES public.jury_profiles(id) ON DELETE CASCADE,
    challenge_category_id bigint NOT NULL REFERENCES public.challenge_categories(id),
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    PRIMARY KEY (jury_profile_id, challenge_category_id)
);

CREATE TABLE IF NOT EXISTS public.jury_verification_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jury_profile_id bigint NOT NULL REFERENCES public.jury_profiles(id) ON DELETE CASCADE,
    token_hash character varying(128) NOT NULL UNIQUE,
    expires_at timestamp with time zone NOT NULL,
    consumed_at timestamp with time zone,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);

CREATE TABLE IF NOT EXISTS public.jury_login_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jury_profile_id bigint NOT NULL REFERENCES public.jury_profiles(id) ON DELETE CASCADE,
    code_hash character varying(128) NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    consumed_at timestamp with time zone,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_jury_profiles_scope_location ON public.jury_profiles(state_id, district_id);
CREATE INDEX IF NOT EXISTS idx_jury_verification_tokens_active ON public.jury_verification_tokens(token_hash, expires_at) WHERE consumed_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_jury_login_tokens_active ON public.jury_login_tokens(jury_profile_id, expires_at) WHERE consumed_at IS NULL;
