BEGIN;

-- One evaluation per application per jury level (District / State). The row is
-- created when a jury member opens the application for evaluation, so its
-- existence is what locks the application against other jury members.
CREATE TABLE IF NOT EXISTS public.jury_evaluations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id bigint NOT NULL REFERENCES public.participant_applications(id) ON DELETE CASCADE,
    jury_profile_id bigint NOT NULL REFERENCES public.jury_profiles(id),
    level character varying(10) NOT NULL,
    status character varying(20) DEFAULT 'in_progress' NOT NULL,
    total_score integer DEFAULT 0 NOT NULL,
    recommendation character varying(20),
    comments text,
    started_at timestamp with time zone DEFAULT now() NOT NULL,
    submitted_at timestamp with time zone,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT ck_jury_evaluations_level CHECK (level IN ('District', 'State', 'Region')),
    CONSTRAINT ck_jury_evaluations_status CHECK (status IN ('in_progress', 'submitted', 'auto_submitted')),
    CONSTRAINT ck_jury_evaluations_total CHECK (total_score BETWEEN 0 AND 100),
    CONSTRAINT ck_jury_evaluations_recommendation CHECK (recommendation IS NULL OR recommendation IN ('Recommend', 'Reject', 'Review')),
    -- An application can only be opened by one jury member per level.
    CONSTRAINT uq_jury_evaluations_application_level UNIQUE (application_id, level)
);

-- A jury member can only have one evaluation in progress at a time; the next
-- application is available once the current one has been finally submitted.
CREATE UNIQUE INDEX IF NOT EXISTS uq_jury_evaluations_one_in_progress
    ON public.jury_evaluations (jury_profile_id)
    WHERE status = 'in_progress';

CREATE INDEX IF NOT EXISTS idx_jury_evaluations_jury ON public.jury_evaluations (jury_profile_id);
CREATE INDEX IF NOT EXISTS idx_jury_evaluations_submitted
    ON public.jury_evaluations (application_id, level)
    WHERE status IN ('submitted', 'auto_submitted');

-- Marks for each evaluation criterion (0 to 10).
CREATE TABLE IF NOT EXISTS public.jury_evaluation_scores (
    evaluation_id bigint NOT NULL REFERENCES public.jury_evaluations(id) ON DELETE CASCADE,
    criterion_key character varying(40) NOT NULL,
    score smallint NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    PRIMARY KEY (evaluation_id, criterion_key),
    CONSTRAINT ck_jury_evaluation_scores_range CHECK (score BETWEEN 0 AND 10),
    CONSTRAINT ck_jury_evaluation_scores_key CHECK (criterion_key IN (
        'problemClarity',
        'innovation',
        'method',
        'feasibility',
        'costEffectiveness',
        'impact',
        'scalability',
        'prototype',
        'readiness',
        'presentation'
    ))
);

