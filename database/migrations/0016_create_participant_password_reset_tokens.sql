CREATE TABLE IF NOT EXISTS public.participant_password_reset_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id bigint NOT NULL,
    email character varying(255) NOT NULL,
    token_hash character varying(128) NOT NULL UNIQUE,
    expires_at timestamp with time zone NOT NULL,
    consumed_at timestamp with time zone,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT fk_participant_password_reset_tokens_participant
        FOREIGN KEY (participant_id)
        REFERENCES public.participants(id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_participant_password_reset_tokens_active
    ON public.participant_password_reset_tokens(token_hash, expires_at)
    WHERE consumed_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_participant_password_reset_tokens_email
    ON public.participant_password_reset_tokens(email);
