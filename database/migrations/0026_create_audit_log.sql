BEGIN;

-- Permanent, append-only audit trail of every state-changing action taken by
-- any actor type (admin, jury, participant, system) across the system. Rows
-- are never updated or deleted. Actor/application/applicant identity is
-- denormalized at write time so a row stays fully readable even after the
-- thing it describes is deleted or renamed.
--
-- NOTE: `details` is this schema's first jsonb column. One-off, intentional
-- exception to the "no jsonb" convention elsewhere: a permanent, schema-less
-- before/after context bag has no good relational equivalent here, and this
-- is the only table in the schema without a stable, enumerable column set.
CREATE TABLE IF NOT EXISTS public.audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    actor_type character varying(20) NOT NULL,
    actor_id bigint,
    actor_name character varying(200),
    actor_email character varying(200),

    -- category: small, stable, CHECK-constrained set driving the UI filter
    -- dropdown. action: free text so the generic hook can synthesize an
    -- entry (e.g. "http.patch") for any route without a migration, while
    -- explicit call sites use descriptive actions (e.g. "application.updated").
    category character varying(30) NOT NULL,
    action character varying(100) NOT NULL,

    http_method character varying(10) NOT NULL,
    route_path character varying(300) NOT NULL,
    status_code smallint NOT NULL,

    -- Nullable: not every audited action is application-scoped.
    -- ON DELETE SET NULL (never CASCADE): deleting an application must
    -- never delete the audit history about it.
    application_id bigint REFERENCES public.participant_applications(id) ON DELETE SET NULL,
    application_number character varying(40),

    -- Denormalized applicant identity for the "filter by applicant full
    -- name / phone number" requirement, and so it survives deletion.
    applicant_full_name character varying(200),
    applicant_phone character varying(20),

    details jsonb,

    created_at timestamp with time zone DEFAULT now() NOT NULL,

    CONSTRAINT ck_audit_log_actor_type CHECK (actor_type IN ('admin', 'jury', 'participant', 'system')),
    CONSTRAINT ck_audit_log_category CHECK (category IN (
        'application', 'jury_evaluation', 'jury_profile', 'user',
        'settings', 'email_notification', 'auth', 'other'
    ))
);

CREATE INDEX IF NOT EXISTS idx_audit_log_actor
    ON public.audit_log (actor_type, actor_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_log_application_number
    ON public.audit_log (application_number) WHERE application_number IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_audit_log_category ON public.audit_log (category, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_log_created_at ON public.audit_log (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_audit_log_search_text
ON public.audit_log (
    LOWER(
        COALESCE(actor_name, '') || ' ' ||
        COALESCE(actor_email, '') || ' ' ||
        COALESCE(application_number, '') || ' ' ||
        COALESCE(applicant_full_name, '') || ' ' ||
        COALESCE(applicant_phone, '')
    )
);

COMMENT ON TABLE public.audit_log IS 'Permanent audit trail of state-changing actions by all actor types. Rows are never updated or deleted.';

COMMIT;
