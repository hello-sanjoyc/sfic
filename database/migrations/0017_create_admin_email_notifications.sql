CREATE TABLE IF NOT EXISTS public.admin_email_notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode character varying(20) NOT NULL,
    name character varying(255),
    sender_name character varying(255) NOT NULL,
    reply_to_email character varying(255) NOT NULL,
    subject character varying(500) NOT NULL,
    body text NOT NULL,
    delivery_mode character varying(20) NOT NULL,
    scheduled_for timestamp with time zone,
    status character varying(30) DEFAULT 'draft' NOT NULL,
    total_recipients integer DEFAULT 0 NOT NULL,
    queued_count integer DEFAULT 0 NOT NULL,
    processing_count integer DEFAULT 0 NOT NULL,
    sent_count integer DEFAULT 0 NOT NULL,
    delivered_count integer,
    failed_count integer DEFAULT 0 NOT NULL,
    skipped_count integer DEFAULT 0 NOT NULL,
    created_by_user_id bigint NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    sent_at timestamp with time zone,
    CONSTRAINT fk_admin_email_notifications_created_by
        FOREIGN KEY (created_by_user_id)
        REFERENCES public.users(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS public.admin_email_notification_recipients (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id bigint NOT NULL,
    recipient_name character varying(255),
    email character varying(255) NOT NULL,
    delivery_status character varying(30) DEFAULT 'Queued' NOT NULL,
    attempt_count integer DEFAULT 0 NOT NULL,
    last_attempt_at timestamp with time zone,
    failure_reason text,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT fk_admin_email_notification_recipients_notification
        FOREIGN KEY (notification_id)
        REFERENCES public.admin_email_notifications(id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_admin_email_notifications_created_at
    ON public.admin_email_notifications(created_at DESC);

CREATE INDEX IF NOT EXISTS idx_admin_email_recipients_notification
    ON public.admin_email_notification_recipients(notification_id);
